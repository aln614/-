'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const html=read('src/renderer/index.html'),app=read('src/renderer/static/app.js'),css=read('src/renderer/static/style.css');
const appearance=read('src/renderer/static/local-appearance.js');
assert.ok(!html.includes('data-skin=') && !html.includes('skinIdSettings') && !html.includes('themeMascotEnabled'),'Bundled skins and mascots are removed');
assert.ok(!app.includes('applySkinSettings') && !app.includes('persistAppearanceSettings'),'Shared theme saving is removed');
assert.ok(!appearance.includes('fetch(') && !appearance.includes('/api/'),'Custom appearances never reach shared server APIs');
assert.ok(html.indexOf('/static/local-appearance.js')<html.indexOf('/static/liquid-glass-bundle.js'),'Local backgrounds load before glass');
assert.ok(css.includes('*::-webkit-scrollbar{width:4px!important;height:4px!important'),'Slim scrollbars remain');
assert.ok(css.includes('*::-webkit-scrollbar-button{display:none!important'),'Scrollbar arrows stay hidden');
console.log('Local appearance wiring and removed skin system passed.');
